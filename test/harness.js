// Loads src/pkjs/index.js in Node with fake Pebble, localStorage, XHR and Clay.
// Message key IDs are derived from package.json the same way the SDK does (10000 + index).
'use strict';

var Module = require('module');
var path = require('path');

var ROOT = path.join(__dirname, '..');
var INDEX = path.join(ROOT, 'src/pkjs/index.js');
var pkg = require(path.join(ROOT, 'package.json'));

var MESSAGE_KEYS = {};
pkg.pebble.messageKeys.forEach(function (name, i) { MESSAGE_KEYS[name] = 10000 + i; });

var current = null; // state of the most recent load(), read by the stubs below

var STUBS = {
  '@rebble/clay': function Clay() {
    this.meta = { userData: {} };
    this.generateUrl = function () { return ''; };
    this.getSettings = function () { return current.settings; };
  },
  'message_keys': MESSAGE_KEYS,
  // src/pkjs/env.js is generated by the build; tests don't need a build.
  './env': { ENV: 'test', LAMBDA_URL: 'https://lambda.test/', AUTH_URL: 'https://auth.test/' }
};

var origResolve = Module._resolveFilename;
Module._resolveFilename = function (request, parent) {
  if (Object.prototype.hasOwnProperty.call(STUBS, request)) return '__stub:' + request;
  return origResolve.apply(this, arguments);
};
Object.keys(STUBS).forEach(function (name) {
  var id = '__stub:' + name;
  require.cache[id] = { id: id, filename: id, loaded: true, exports: STUBS[name] };
});

// handler(xhr, body) returns [status, responseText]. Default: 200 with empty data.
function load(opts) {
  opts = opts || {};
  current = {
    store: Object.assign({}, opts.store),
    settings: opts.settings || {},
    handler: opts.handler || function () { return [200, '{"data":{}}']; },
    listeners: {},
    sent: [],
    reqs: []
  };
  var s = current;

  global.localStorage = {
    getItem: function (k) { return k in s.store ? s.store[k] : null; },
    setItem: function (k, v) { s.store[k] = String(v); },
    removeItem: function (k) { delete s.store[k]; }
  };
  global.Pebble = {
    addEventListener: function (name, fn) { s.listeners[name] = fn; },
    sendAppMessage: function (msg, ok) { s.sent.push(msg); if (ok) ok(); },
    openURL: function () {}
  };
  global.XMLHttpRequest = function () {
    var x = this;
    var headers = {};
    x.open = function (method, url) { x.method = method; x.url = url; };
    x.setRequestHeader = function (k, v) { headers[k] = v; };
    x.send = function (body) {
      s.reqs.push({ method: x.method, url: x.url, auth: headers.Authorization, body: body });
      setImmediate(function () {
        var r = s.handler(x, body);
        x.status = r[0];
        x.responseText = r[1];
        x.onload();
      });
    };
  };

  delete require.cache[INDEX];
  var quiet = console.log;
  console.log = function () {};
  try {
    require(INDEX);
  } finally {
    console.log = quiet;
  }

  s.setSettings = function (v) { s.settings = v; };
  // Runs a listener with console.log muted, then lets pending XHR callbacks finish.
  s.fire = function (name, event, rounds) {
    var log = console.log;
    console.log = function () {};
    return Promise.resolve()
      .then(function () { s.listeners[name](event); })
      .then(function () { return tick(rounds || 20); })
      .finally(function () { console.log = log; });
  };
  return s;
}

function tick(rounds) {
  var p = Promise.resolve();
  for (var i = 0; i < rounds; i++) {
    p = p.then(function () { return new Promise(function (r) { setImmediate(r); }); });
  }
  return p;
}

// A logged-in phone: valid token for an hour.
function loggedIn(extra) {
  return Object.assign({
    revolver_vin: 'VIN1',
    revolver_access_token: 'OLD',
    revolver_refresh_token: 'RT1',
    revolver_vcc_api_key: 'K',
    revolver_expires_at: String(Math.floor(Date.now() / 1000) + 3600)
  }, extra);
}

module.exports = { load: load, loggedIn: loggedIn, MESSAGE_KEYS: MESSAGE_KEYS };
